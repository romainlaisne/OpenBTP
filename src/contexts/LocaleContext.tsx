interface LocaleContextValue {
  locale: AppLocale
  setLocale: (locale: AppLocale) => void
  t: (key: string, values?: Record<string, string>) => string
  uiTranslationsEnabled: boolean
}

const LocaleContext = createContext<LocaleContextValue | null>(null)

export function LocaleProvider({ children, uiTranslationsEnabled = true }: { children: ReactNode; uiTranslationsEnabled?: boolean }) {
  const [locale, setLocaleState] = useState<AppLocale>('en')

  useEffect(() => {
    try {
      const savedLocale = window.localStorage.getItem('openbtp-locale')
      if (savedLocale === 'fr' || savedLocale === 'en') setLocaleState(savedLocale)
    } catch {
      // Keep the default locale when browser storage is unavailable.
    }
  }, [])

  const setLocale = useCallback((nextLocale: AppLocale) => {
    setLocaleState(nextLocale)
    try {
      window.localStorage.setItem('openbtp-locale', nextLocale)
    } catch {
      // The current page still switches language without persistent storage.
    }
    document.documentElement.lang = nextLocale
  }, [])

  const t = useCallback((key: string, values?: Record<string, string>) => {
    const template = messages[locale][key] ?? messages.fr[key] ?? key
    return Object.entries(values ?? {}).reduce(
      (message, [name, value]) => message.replaceAll(`{${name}}`, value),
      template,
    )
  }, [locale])

  const value = useMemo(() => ({ locale, setLocale, t, uiTranslationsEnabled }), [locale, setLocale, t, uiTranslationsEnabled])

  useEffect(() => {
    document.documentElement.lang = locale
  }, [locale])

  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>
}

export function UiText({ children }: { children: string }) {
  const { locale, uiTranslationsEnabled } = useLocale()
  return <>{localizeUiText(children, locale, uiTranslationsEnabled)}</>
}

export function useLocale() {
  const context = useContext(LocaleContext)
  if (!context) throw new Error('useLocale must be used within LocaleProvider')
  return context
}