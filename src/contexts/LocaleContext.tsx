export function localizeUiText(text: string | undefined, locale: AppLocale, enabled = true) {
  if (!text || !enabled || locale === 'fr') return text ?? ''
  const leading = text.match(/^\s*/)?.[0] ?? ''
  const trailing = text.match(/\s*$/)?.[0] ?? ''
  const content = text.slice(leading.length, text.length - trailing.length || undefined)
  const translated = uiTranslations[content] ?? translateDynamicUiText(content)
  return `${leading}${translated}${trailing}`
}

function translateDynamicUiText(text: string) {
  if (text.startsWith('Chantier : ')) return `Project: ${text.slice('Chantier : '.length)}`
  if (text.startsWith('Visite du ')) return `Visit on ${text.slice('Visite du '.length)}`
  if (text.startsWith('Ouvrier chez ')) return `Worker at ${text.slice('Ouvrier chez '.length)}`

  const createdMatch = text.match(/^Créé le (.+) par (.+)$/)
  if (createdMatch) return `Created on ${createdMatch[1]} by ${createdMatch[2]}`

  const measurementMatch = text.match(/^Métré soumis par (.+) pour (.+)$/)
  if (measurementMatch) return `Measurement submitted by ${measurementMatch[1]} for ${measurementMatch[2]}`

  return text
}

